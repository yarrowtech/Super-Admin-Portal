test('encryption, SSRF restrictions and response field filtering', () => {
  const value = security.encrypt('provider-secret-value');
  assert.equal(security.decrypt(value), 'provider-secret-value');
  assert.ok(!value.includes('provider-secret-value'));
  const parts = value.split('.'); parts[2] = Buffer.from('tampered').toString('base64');
  assert.throws(() => security.decrypt(parts.join('.')));
  for (const address of ['127.0.0.1', '10.1.2.3', '169.254.169.254', '172.16.1.1', '192.168.0.1', '::1', '::ffff:127.0.0.1', '100.64.0.1']) assert.equal(security.publicAddress(address), false, address);
  assert.equal(security.publicAddress('8.8.8.8'), true);
  assert.throws(() => security.baseUrl('http://example.com'));
  assert.throws(() => security.baseUrl('https://user:secret@example.com'));
  assert.throws(() => security.baseUrl('https://127.1'));
  assert.deepEqual(security.projectResponse({ data: [{ name: 'Approved', secret: 'hidden' }] }, { recordsPath: 'data', responseSchema: { name: 'string' } }, ['name']), [{ name: 'Approved' }]);
  assert.throws(() => security.projectResponse({ name: { secret: 'hidden' } }, { responseSchema: { name: 'string' } }, ['name']));
});

