const express = require('express');
const { authenticate } = require('../middlewares/auth.middleware');
const controller = require('../controllers/yarrowtech.controller');
const router = express.Router();
router.use(authenticate);
router.get('/projects/:projectId/overview', controller.overview);
router.get('/projects/:projectId/service-clients', controller.clients);
router.get('/projects/:projectId/service-projects', controller.deliveries);
router.post('/projects/:projectId/service-projects', controller.createDelivery);
router.patch('/service-projects/:resourceId', controller.updateDelivery);
router.post('/services/:resourceId/archive', controller.archive('service'));
router.post('/products/:resourceId/archive', controller.archive('product'));
router.get('/services/:resourceId/settings', controller.settings('service'));
router.patch('/services/:resourceId/settings', controller.saveSettings('service'));
router.get('/products/:resourceId/settings', controller.settings('product'));
router.patch('/products/:resourceId/settings', controller.saveSettings('product'));
router.get('/subscriptions/:resourceId/payments', controller.payments);
router.get('/projects/:projectId/provider-projects', controller.projects);
router.get('/provider-projects/:resourceId', controller.project);
router.patch('/provider-projects/:resourceId', controller.updateProject);
router.get('/projects/:projectId/activity', controller.audit);
router.get('/projects/YARROWTECH/audit-logs', controller.audit);
router.get('/projects/:projectId/sync-history', controller.syncHistory);
router.get('/integrations/yarrowtech-srs', controller.integration);
router.patch('/integrations/yarrowtech-srs', controller.configureIntegration);
router.post('/projects/:projectId/integrations', (req, res, next) => req.body?.integrationId === 'yarrowtech-srs' ? controller.configureIntegration(req, res, next) : next());
router.get('/integrations/yarrowtech-srs/status', controller.integration);
router.get('/integrations/yarrowtech-srs/capabilities', controller.capabilities);
router.post('/integrations/yarrowtech-srs/test-connection', controller.testConnection);
router.post('/integrations/yarrowtech-srs/authorize', controller.testConnection);
router.post('/integrations/yarrowtech-srs/sync', controller.sync);
router.get('/integrations/:integrationId/sync-jobs', (req, res, next) => req.params.integrationId === 'yarrowtech-srs' ? controller.syncHistory(req, res, next) : next());
router.get('/integrations/yarrowtech-srs/records', controller.integrationRecords);
module.exports = router;
